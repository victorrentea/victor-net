import AppKit
import CryptoKit
import Foundation

/// One clip as both ends seal it. The phone's half is `ClipSync.kt`, same format.
struct ClipEnvelope: Codable, Equatable {
    let id: String
    /// Milliseconds since 1970, compared by the reader to refuse a replay.
    let ts: Int64
    let from: String
    let text: String
    /// Set instead of `text` when the phone offers files (`FileInbox`).
    var files: [FileOffer]? = nil
    /// Where the phone can be reached for them.
    var ips: [String]? = nil
    /// The files wait on Railway instead: the phone found no shorter way.
    var relay: Bool? = nil
}

/// AES-256-GCM: nonce + ciphertext + tag, as base64url without padding.
enum ClipCrypto {
    static func key(hex: String) -> SymmetricKey? {
        guard hex.count == 64 else { return nil }
        var bytes = [UInt8]()
        var i = hex.startIndex
        while i < hex.endIndex {
            let next = hex.index(i, offsetBy: 2)
            guard let b = UInt8(hex[i..<next], radix: 16) else { return nil }
            bytes.append(b)
            i = next
        }
        return SymmetricKey(data: bytes)
    }

    static func seal(_ clip: ClipEnvelope, key: SymmetricKey) throws -> String {
        let combined = try AES.GCM.seal(JSONEncoder().encode(clip), using: key).combined!
        return combined.base64EncodedString()
            .replacingOccurrences(of: "+", with: "-")
            .replacingOccurrences(of: "/", with: "_")
            .replacingOccurrences(of: "=", with: "")
    }

    static func open(_ sealed: String, key: SymmetricKey) -> ClipEnvelope? {
        var b64 = sealed.replacingOccurrences(of: "-", with: "+").replacingOccurrences(of: "_", with: "/")
        b64 += String(repeating: "=", count: (4 - b64.count % 4) % 4)
        guard let data = Data(base64Encoded: b64),
              let box = try? AES.GCM.SealedBox(combined: data),
              let plain = try? AES.GCM.open(box, using: key) else { return nil }
        return try? JSONDecoder().decode(ClipEnvelope.self, from: plain)
    }
}

/// What gets sent and what gets believed. No pasteboard and no sockets, so a test can pin it.
enum ClipPolicy {
    static let maxText = 128 * 1024
    /// `R /clip?c=…` crosses a slow channel that waits 1.5 s for the whole line.
    static let maxBluetoothCiphertext = 900
    /// A copy has to stay this long: apps that paste by borrowing the clipboard put it back sooner.
    static let settle: TimeInterval = 0.6
    static let maxAge: TimeInterval = 600

    /// `nspasteboard.org` markers for content the source itself calls throwaway.
    private static let throwaway: Set<String> = ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    static func shouldSend(text: String?, types: [String], lastSynced: String?) -> Bool {
        guard let text, !text.isEmpty, text.count <= maxText, text != lastSynced else { return false }
        return throwaway.isDisjoint(with: types)
    }

    static func believable(_ clip: ClipEnvelope, now: Date, seen: [String]) -> Bool {
        let age = abs(now.timeIntervalSince1970 - Double(clip.ts) / 1000)
        return clip.from == "phone" && age < maxAge && !seen.contains(clip.id)
    }
}

/// 📋 The clipboard, shared with the phone. Docs: docs/clipboard.md.
///
/// A text copied here goes to the phone at once: straight to it on its hotspot, always to
/// the Railway mailbox, and over Bluetooth only when the mailbox could not be reached.
/// Text from the phone comes through the mailbox, long-polled. Everything is sealed with
/// `CLIP_KEY`, which the mailbox never sees. No key = off. Clips are never logged.
final class ClipSync {
    private static let tick: TimeInterval = 0.2
    private static let waitS = 45
    private static let retry: TimeInterval = 15

    private let phone: PhoneLink
    let inbox = FileInbox()
    let toast = ClipToast()
    private let key: SymmetricKey?
    private let pasteboard = NSPasteboard.general
    private lazy var session: URLSession = {
        let c = URLSessionConfiguration.ephemeral
        c.timeoutIntervalForRequest = TimeInterval(Self.waitS + 15)
        c.waitsForConnectivity = false
        return URLSession(configuration: c)
    }()
    private var timer: Timer?
    private var changeCount = 0
    private var changedAt: Date?
    private var lastSynced: String?
    private var after = -1
    /// The first answer only says where the mailbox stands: what it holds predates this run,
    /// and a restart must not paste an old clip over whatever the clipboard has now.
    private var primed = false
    private var seen: [String] = []
    private var lastSent: (Date, String)?
    private var lastReceived: Date?
    private var lastError: String?

    var onHotspot: () -> Bool = { false }

    init(phone: PhoneLink) {
        self.phone = phone
        key = ClipCrypto.key(hex: Config.clipKey)
    }

    var stateJSON: [String: Any] {
        ["on": key != nil,
         "last_sent_ago_s": orNull(lastSent.map { Int(Date().timeIntervalSince($0.0)) }),
         "last_sent_via": orNull(lastSent?.1),
         "last_received_ago_s": orNull(lastReceived.map { Int(Date().timeIntervalSince($0)) }),
         "last_error": orNull(lastError),
         "toast_ago_s": orNull(toast.lastShown.map { Int(Date().timeIntervalSince($0.0)) }),
         "toast_link": orNull(toast.lastShown?.1),
         "files": inbox.stateJSON]
    }

    func start() {
        guard key != nil, !Config.relayURL.isEmpty, !Config.relayToken.isEmpty else { return }
        changeCount = pasteboard.changeCount
        lastSynced = pasteboard.string(forType: .string)
        let t = Timer(timeInterval: Self.tick, repeats: true) { [weak self] _ in self?.watch() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
        poll()
    }

    // MARK: - This Mac → the phone

    private func watch() {
        if pasteboard.changeCount != changeCount {
            changeCount = pasteboard.changeCount
            changedAt = Date()
        }
        guard let at = changedAt, Date().timeIntervalSince(at) >= ClipPolicy.settle else { return }
        changedAt = nil
        let text = pasteboard.string(forType: .string)
        guard ClipPolicy.shouldSend(text: text, types: pasteboard.types?.map(\.rawValue) ?? [], lastSynced: lastSynced),
              let text, let key else { return }
        lastSynced = text
        let clip = ClipEnvelope(id: UUID().uuidString, ts: Int64(Date().timeIntervalSince1970 * 1000), from: "mac", text: text)
        guard let sealed = try? ClipCrypto.seal(clip, key: key) else { return }
        send(sealed)
    }

    private func send(_ sealed: String) {
        if onHotspot() { phone.clip(sealed) { [weak self] _, why in self?.sent("hotspot", why) } }
        putInMailbox(sealed) { [weak self] ok in
            guard let self else { return }
            if ok { return self.sent("mailbox", nil) }
            guard !self.onHotspot(), sealed.count <= ClipPolicy.maxBluetoothCiphertext else {
                return self.sent("nothing", "the mailbox did not answer")
            }
            self.phone.clip(sealed) { [weak self] _, why in self?.sent("bluetooth", why) }
        }
    }

    private func sent(_ via: String, _ why: String?) {
        if let why { netInfo("📋 clip via \(via): \(why)") } else { lastSent = (Date(), via) }
        lastError = why
    }

    private func putInMailbox(_ sealed: String, done: @escaping (Bool) -> Void) {
        guard let url = URL(string: "\(Config.relayURL)/api/clip/phone") else { return done(false) }
        var request = URLRequest(url: url)
        request.httpMethod = "PUT"
        request.timeoutInterval = 8
        request.setValue(Config.relayToken, forHTTPHeaderField: "X-Bridge-Token")
        request.setValue("application/json", forHTTPHeaderField: "Content-Type")
        request.httpBody = try? JSONEncoder().encode(["ciphertext": sealed])
        session.dataTask(with: request) { _, response, _ in
            let ok = (response as? HTTPURLResponse)?.statusCode == 200
            RunLoop.main.perform(inModes: [.common]) { done(ok) }
            CFRunLoopWakeUp(CFRunLoopGetMain())
        }.resume()
    }

    // MARK: - The phone → this Mac

    private func poll() {
        guard let url = URL(string: "\(Config.relayURL)/api/clip/mac?after=\(after)&wait=\(primed ? Self.waitS : 0)") else { return }
        var request = URLRequest(url: url)
        request.setValue(Config.relayToken, forHTTPHeaderField: "X-Bridge-Token")
        session.dataTask(with: request) { [weak self] data, response, _ in
            let answer = (response as? HTTPURLResponse)?.statusCode == 200
                ? data.flatMap { try? JSONSerialization.jsonObject(with: $0) as? [String: Any] } : nil
            RunLoop.main.perform(inModes: [.common]) { self?.polled(answer) }
            CFRunLoopWakeUp(CFRunLoopGetMain())
        }.resume()
    }

    private func polled(_ answer: [String: Any]?) {
        guard let answer else {
            let t = Timer(timeInterval: Self.retry, repeats: false) { [weak self] _ in self?.poll() }
            RunLoop.main.add(t, forMode: .common)
            return
        }
        after = answer["seq"] as? Int ?? after
        defer { primed = true }
        if primed, let sealed = answer["ciphertext"] as? String { take(sealed) }
        poll()
    }

    /// `/status` shows the phone's file offers too: on its hotspot there may be no mailbox.
    func status(_ data: Data) {
        guard let o = (try? JSONSerialization.jsonObject(with: data)) as? [String: Any],
              let offers = o["files"] as? [String] else { return }
        offers.forEach(take)
    }

    private func take(_ sealed: String) {
        guard let key, let clip = ClipCrypto.open(sealed, key: key),
              ClipPolicy.believable(clip, now: Date(), seen: seen) else { return }
        // A file offer is not marked seen: `/status` repeats it every 5 s, which is the retry
        // after a failed download. `FileInbox` itself skips a file it has or is fetching.
        if let files = clip.files { return inbox.accept(files, ips: clip.ips ?? [], relay: clip.relay ?? false) }
        seen = Array((seen + [clip.id]).suffix(64))
        write(clip.text)
    }

    private func write(_ text: String) {
        pasteboard.clearContents()
        pasteboard.declareTypes([.string, NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")], owner: nil)
        pasteboard.setString(text, forType: .string)
        changeCount = pasteboard.changeCount
        lastSynced = text
        lastReceived = Date()
        toast.show(text)
    }
}
